"""Generate explicit kernel API scheduling boundaries; fails on an unguarded ABI addition."""
import argparse,json,re
from pathlib import Path
root=Path(__file__).resolve().parents[1]
header=(root/'sdk/sacx/include/sacx_api.h').read_text()
header=header[re.search(r'\bstruct sacx_api\s*\{',header).start():]
targets=json.loads((root/'tools/sacx_api_guard_targets.json').read_text())
functions=re.findall(r'^\s*([A-Za-z_][A-Za-z_0-9 \t*]*?)\s*\(\*(\w+)\)\((.*?)\);',header,re.M|re.S)
output='/* Generated by tools/generate_sacx_api_guards.py. */\n'
seen=set()
for result,name,args in functions:
    if name in ('app_checkpoint','app_yield'):continue
    if name not in targets:raise SystemExit(f'Missing scheduling boundary target for ABI field {name}')
    seen.add(name);args=' '.join(args.split());forward=[]
    if args!='void':
        for arg in args.split(','):
            match=re.search(r'(\w+)\s*(?:\[[^]]*\])?$',arg)
            if not match:raise ValueError(arg)
            forward.append(match[1])
    call=targets[name]+'('+','.join(forward)+')'
    output+=f'static {result} sacx_guard_{name}({args}) {{\n'
    output+='    sacx_task *owner=smp_current_logical_id()==0u ? G_current_task:0;\n    const char *prior=owner ? owner->active_api:0;\n'
    output+=f'    if(owner){{owner->active_api="{name}";++owner->api_depth;}}\n'
    output+=f'    {"" if result=="void" else result+" result="}{call};\n'
    output+=f'    if(owner){{--owner->api_depth;owner->last_api="{name}";owner->active_api=prior;}}\n'
    if result!='void':output+='    return result;\n'
    output+='}\n'
if seen!=targets.keys():raise SystemExit('Stale or missing API guard targets: '+str(seen ^ targets.keys()))
ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');a=ap.parse_args()
path=root/'kernel/apps/sacx_api_guards.inc'
if a.check:
    if path.read_text()!=output:raise SystemExit('Stale ABI guards; regenerate with tools/generate_sacx_api_guards.py')
else:path.write_text(output)
