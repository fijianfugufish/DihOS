"""Independent Python-integer oracle for native compiler-rt 128-bit division."""
import argparse,random
from pathlib import Path
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
out=Path(__file__).with_name('user_arithmetic_vectors.inc')
rng=random.Random(0xD1A05);mask=(1<<128)-1
def words(value):
    value &= mask
    return [value>>64,value&((1<<64)-1)]
def emit(name,rows):
    text=['static const ArithmeticCase '+name+'[]={']
    for a,b,q,r in rows:
        values=words(a)+words(b)+words(q)+words(r)
        text.append('    {'+','.join('0x%016xULL'%value for value in values)+'},')
    return '\n'.join(text+['};',''])
unsigned=[];signed=[]
for i in range(64):
    a=rng.getrandbits(128)
    b=(rng.getrandbits(8 if i%4==0 else 128) or 1)
    unsigned.append((a,b,a//b,a%b))
    a=rng.randrange(-(1<<127),1<<127)
    b=rng.randrange(-(1<<127),1<<127) or 1
    if i%4==0:b=(-1 if i%8 else 1)*(rng.getrandbits(8) or 1)
    q=abs(a)//abs(b)
    if (a<0)!=(b<0):q=-q
    signed.append((a,b,q,a-q*b))
text='// Generated by generate_user_arithmetic_vectors.py; Python big-integer oracle.\n'+emit('unsigned_cases',unsigned)+emit('signed_cases',signed)
if args.check:
    if not out.exists() or out.read_text()!=text:raise SystemExit('Stale arithmetic oracle vectors')
else:out.write_text(text)
print('PASS: 128 independent 128-bit arithmetic oracle vectors')
