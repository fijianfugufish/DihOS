"""Generate the complete FPSIMD/GPR EL0 frame and EL1 return assembly."""
from pathlib import Path
import argparse
root=Path(__file__).resolve().parents[1]
def instruction(line):return '        "'+line+'\\n"\n'
def emit(name,instructions,ret='void'):
    return f'{ret} {name}\n{{\n    __asm__ volatile(\n'+''.join(instruction(s) for s in instructions)+');\n}\n'
save=['sub sp,sp,#832']
for i in range(0,30,2):save+=[f'stp x{i},x{i+1},[sp,#{i*8}]']
save+=['str x30,[sp,#240]']
for register,offset in [('esr_el1',248),('far_el1',256),('elr_el1',264),('spsr_el1',272),('sp_el0',280),('fpcr',800),('fpsr',808),('tpidr_el0',816)]:save += [f'mrs x9,{register}',f'str x9,[sp,#{offset}]']
for i in range(0,32,2):save += [f'stp q{i},q{i+1},[sp,#{288+i*16}]']
restore=[]
for register,offset in [('elr_el1',264),('spsr_el1',272),('sp_el0',280),('fpcr',800),('fpsr',808),('tpidr_el0',816)]:restore += [f'ldr x9,[sp,#{offset}]',f'msr {register},x9']
for i in range(0,32,2):restore += [f'ldp q{i},q{i+1},[sp,#{288+i*16}]']
for i in range(0,30,2):restore += [f'ldp x{i},x{i+1},[sp,#{i*8}]']
restore+=['ldr x30,[sp,#240]','add sp,sp,#832']
out='/* Generated by tools/generate_user_vectors.py. */\n'
for name,irq in [('aa64_user_slice_sync_vector',0),('aa64_user_slice_irq_vector',1)]:
    out+='__attribute__((naked)) '+emit(name+'(void)',save+['mov x0,sp',f'mov x1,#{irq}','bl user_slice_dispatch','cbz x0,1f']+restore+['eret','1:']+restore+['b aa64_exception_common'])
entry=['adrp x9,user_return','add x9,x9,:lo12:user_return','mrs x10,ttbr0_el1','str x10,[x9,#0]','mrs x10,daif','str x10,[x9,#8]','str x18,[x9,#16]']
for i in range(19,31,2):entry+=[f'stp x{i},x{i+1},[x9,#{24+(i-19)*8}]']
for i in range(8,16,2):entry+=[f'stp d{i},d{i+1},[x9,#{120+(i-8)*8}]']
for register,offset in [('fpcr',184),('fpsr',192),('tpidr_el0',200),('cpacr_el1',208)]:entry += [f'mrs x10,{register}',f'str x10,[x9,#{offset}]']
entry+=['str x0,[x9,#216]','mov x12,#3','lsl x12,x12,#16','bic x10,x10,x12','lsl x12,x12,#8','bic x10,x10,x12','orr x10,x10,#0x300000','msr cpacr_el1,x10','isb','ldr x10,[x0,#832]','dsb ishst','msr ttbr0_el1,x10','isb','tlbi vmalle1is','dsb ish','isb','mov x30,x0']
for register,offset in [('elr_el1',264),('spsr_el1',272),('sp_el0',280),('fpcr',800),('fpsr',808),('tpidr_el0',816)]:entry += [f'ldr x9,[x30,#{offset}]',f'msr {register},x9']
for i in range(0,32,2):entry += [f'ldp q{i},q{i+1},[x30,#{288+i*16}]']
for i in range(0,28,2):entry += [f'ldp x{i},x{i+1},[x30,#{i*8}]']
entry+=['ldr x28,[x30,#864]','msr cntv_tval_el0,x28','mov x28,#1','msr cntv_ctl_el0,x28','isb','ldp x28,x29,[x30,#224]','ldr x30,[x30,#240]','eret']
out+='static '+emit('user_enter_slice(aa64_user_cpu *task)',entry,'int')
ret=['adrp x9,user_return','add x9,x9,:lo12:user_return','str xzr,[x9,#216]']
for register,offset in [('fpcr',184),('fpsr',192),('tpidr_el0',200),('cpacr_el1',208)]:ret += [f'ldr x10,[x9,#{offset}]',f'msr {register},x10']
for i in range(8,16,2):ret += [f'ldp d{i},d{i+1},[x9,#{120+(i-8)*8}]']
ret+=['ldr x18,[x9,#16]']
for i in range(19,31,2):ret += [f'ldp x{i},x{i+1},[x9,#{24+(i-19)*8}]']
ret+=['ldr x0,[x9,#224]','ldr x10,[x9,#8]','msr daif,x10','isb','ret']
out+='static '+emit('user_return_trampoline(void)',ret)
p=root/'kernel/asm/aa64/aa64_user_vectors.inc'
ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');args=ap.parse_args()
if args.check:
    if p.read_text()!=out:raise SystemExit('Stale EL0 vector assembly')
else:p.write_text(out)
