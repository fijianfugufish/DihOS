"""Independent Gregorian calendar vectors from Python's UTC datetime model."""
from datetime import datetime, timezone
from pathlib import Path
import argparse

parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
origin = datetime(1970, 1, 1, tzinfo=timezone.utc)
lines = ['// Generated by generate_user_calendar_vectors.py; UTC, no host timezone.']
for year in range(1, 10000, 37):
    for month, day in [(1, 1), (2, 28), (3, 1), (12, 31)]:
        value = datetime(year, month, day, 12, 34, 56, tzinfo=timezone.utc)
        delta = value - origin
        seconds = delta.days * 86400 + delta.seconds
        fields = [year, month, day, 12, 34, 56, (value.weekday() + 1) % 7,
                  value.timetuple().tm_yday - 1]
        lines.append('{' + str(seconds) + 'll,' + ','.join(map(str, fields)) + '},')
text = '\n'.join(lines) + '\n'
path = Path(__file__).with_name('user_calendar_vectors.inc')
if args.check:
    if not path.exists() or path.read_text() != text:
        raise SystemExit('Stale native calendar test vectors; run the generator')
elif not path.exists() or path.read_text() != text:
    path.write_text(text)
print(f'PASS: {len(lines)-1} independent UTC date vectors')
