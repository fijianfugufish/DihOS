"""Owned, deterministic tiny images for native decoder/rendering tests (Pillow)."""
from pathlib import Path
from io import BytesIO
from PIL import Image
import hashlib,json
root=Path(__file__).resolve().parents[1]
out=root/'tools/browser_fixtures/images';out.mkdir(parents=True,exist_ok=True)
header=['/* Generated by tools/make_browser_image_fixtures.py; owned test pixels. */']
records={}
for fmt in ['PNG','JPEG','GIF','BMP','WEBP']:
    image=Image.new('RGB',(4,4),(240,32,16));stream=BytesIO()
    image.save(stream,format=fmt,**({'lossless':True} if fmt=='WEBP' else {}))
    data=stream.getvalue();name=fmt.lower();(out/('red.'+name)).write_bytes(data)
    header.append('static const unsigned char image_'+name+'[]={'+','.join(map(str,data))+'};')
    records[name]={'bytes':len(data),'sha256':hashlib.sha256(data).hexdigest()}
svg=b'<svg xmlns="http://www.w3.org/2000/svg" width="4" height="4"><rect width="4" height="4" fill="#2060e0"/></svg>'
stream=BytesIO();Image.new('RGBA',(1,1),(200,100,50,128)).save(stream,format='PNG')
header.append('static const unsigned char image_alpha[]={'+','.join(map(str,stream.getvalue()))+'};')
(out/'blue.svg').write_bytes(svg);header.append('static const unsigned char image_svg[]={'+','.join(map(str,svg))+'};')
(out/'fixtures.inc').write_text('\n'.join(header)+'\n')
(out/'manifest.json').write_text(json.dumps(records,indent=2)+'\n')
